"""Runtime bootstrap generator for O(1) DLL registration and hermetic path projection."""

from __future__ import annotations

import sys
from pathlib import Path


class BootstrapGenerator:
    """Creates and updates the vendor runtime __bootstrap__.py and sitecustomize.py loaders."""

    def __init__(self, vendor_root: Path) -> None:
        """Initialize generator with vendor directory path."""
        self._vendor_root = vendor_root

    def generate(
        self,
        dll_subdirectories: list[str] | None = None,
        hermetic: bool = True,
    ) -> Path:
        """Write deterministic O(1) runtime bootstrap script."""
        bootstrap_file = self._vendor_root / "__bootstrap__.py"
        init_file = self._vendor_root / "__init__.py"

        subdirs = sorted(set(dll_subdirectories or []))
        expected_py = f"{sys.version_info.major}.{sys.version_info.minor}"

        content = (
            '"""Automatic runtime path and O(1) DLL directory injector generated by VNMA."""\n\n'
            "import os\n"
            "import site\n"
            "import sys\n"
            "import sysconfig\n"
            "import warnings\n"
            "from pathlib import Path\n\n"
            "_VENDOR_DIR = Path(__file__).resolve().parent\n"
            "_VENDOR_STR = str(_VENDOR_DIR)\n"
            f"_EXPECTED_PY_MM = {expected_py!r}\n"
            f"_HERMETIC_DEFAULT = {hermetic!r}\n"
            f"_DLL_SUBDIRS = {subdirs!r}\n"
            "_DLL_HANDLES = []\n"
            "_BOOTSTRAPPED = False\n\n"
            "def _check_abi_compatibility() -> None:\n"
            '    current_mm = f"{sys.version_info.major}.{sys.version_info.minor}"\n'
            "    if current_mm != _EXPECTED_PY_MM:\n"
            "        warnings.warn(\n"
            '            f"[vnma] vendor/ was built for Python {_EXPECTED_PY_MM}, "\n'
            '            f"but runtime is Python {current_mm}. Compiled extensions (.pyd/.so) may fail. "\n'
            '            "Run \'vnma install .\' to rebuild.",\n'
            "            RuntimeWarning,\n"
            "            stacklevel=2,\n"
            "        )\n\n"
            "def _apply_hermetic_projection() -> None:\n"
            '    if os.environ.get("VNMA_HERMETIC", "1" if _HERMETIC_DEFAULT else "0") != "1":\n'
            "        if _VENDOR_STR not in sys.path:\n"
            "            sys.path.insert(0, _VENDOR_STR)\n"
            "        return\n\n"
            "    forbidden = set()\n"
            '    for key in ("purelib", "platlib"):\n'
            "        p = sysconfig.get_path(key)\n"
            "        if p:\n"
            "            forbidden.add(os.path.normcase(os.path.abspath(p)))\n"
            "    user_site_getter = getattr(site, 'getusersitepackages', None)\n"
            "    if callable(user_site_getter):\n"
            "        u = user_site_getter()\n"
            "        if isinstance(u, str):\n"
            "            forbidden.add(os.path.normcase(os.path.abspath(u)))\n\n"
            "    clean_path = [_VENDOR_STR, str(_VENDOR_DIR.parent)]\n"
            "    for entry in sys.path:\n"
            "        if not entry:\n"
            "            continue\n"
            "        norm_entry = os.path.normcase(os.path.abspath(entry))\n"
            "        if norm_entry == os.path.normcase(_VENDOR_STR):\n"
            "            continue\n"
            "        is_forbidden = any(\n"
            "            norm_entry == fp or norm_entry.startswith(fp + os.sep)\n"
            "            for fp in forbidden\n"
            '        ) or ("site-packages" in norm_entry or "dist-packages" in norm_entry)\n\n'
            "        if not is_forbidden:\n"
            "            if entry not in clean_path:\n"
            "                clean_path.append(entry)\n\n"
            "    sys.path[:] = clean_path\n\n"
            "def _register_dll_directories() -> None:\n"
            "    if sys.platform != 'win32' or not hasattr(os, 'add_dll_directory'):\n"
            "        return\n"
            "    real_vendor = os.path.realpath(_VENDOR_STR)\n"
            "    for rel in _DLL_SUBDIRS:\n"
            "        candidate = os.path.realpath(os.path.join(real_vendor, rel)) if rel else real_vendor\n"
            "        if os.path.commonpath([real_vendor, candidate]) != real_vendor:\n"
            "            continue\n"
            "        if os.path.isdir(candidate):\n"
            "            try:\n"
            "                _DLL_HANDLES.append(os.add_dll_directory(candidate))\n"
            "            except OSError:\n"
            "                pass\n\n"
            "def bootstrap() -> None:\n"
            "    global _BOOTSTRAPPED\n"
            "    if _BOOTSTRAPPED:\n"
            "        return\n"
            "    _check_abi_compatibility()\n"
            "    _apply_hermetic_projection()\n"
            "    _register_dll_directories()\n"
            "    _BOOTSTRAPPED = True\n\n"
            "bootstrap()\n"
        )

        bootstrap_file.write_text(content, encoding="utf-8")

        init_content = (
            '"""Vendor package root initialization."""\n\n'
            "from . import __bootstrap__  # noqa: F401\n"
        )
        if not init_file.exists():
            init_file.write_text(init_content, encoding="utf-8")

        site_dir = self._vendor_root / ".vnma_meta" / "site"
        site_dir.mkdir(parents=True, exist_ok=True)
        sitecustomize = site_dir / "sitecustomize.py"
        sitecustomize.write_text(
            "import sys\n"
            "from pathlib import Path\n"
            "_VENDOR = Path(__file__).resolve().parents[2]\n"
            "if str(_VENDOR) not in sys.path:\n"
            "    sys.path.insert(0, str(_VENDOR))\n"
            "import __bootstrap__  # noqa: F401\n",
            encoding="utf-8",
        )

        return bootstrap_file
